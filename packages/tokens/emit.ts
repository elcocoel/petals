// Writes apps/web/app/tokens.generated.css from source.ts (T175).
//   node packages/tokens/emit.ts           regenerate
//   node packages/tokens/emit.ts --check   exit 1 if it's stale, or a contrast pair is too low
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import {
  breakpoints,
  contrastMinimum,
  contrastPairs,
  cornerRadius,
  figureScale,
  fonts,
  kebab,
  opacity,
  type Paint,
  type Primitive,
  paintCss,
  type Role,
  type Roles,
  rendererVariables,
  roleUtilities,
  type SurfaceName,
  splitText,
  stroke,
  type Tokens,
  tokens,
  wordmark,
} from './source.ts';

export const OUTPUT = fileURLToPath(
  new URL('../../apps/web/app/tokens.generated.css', import.meta.url),
);

const block = (selector: string, lines: string[]) =>
  [`${selector} {`, ...lines.map((l) => `  ${l}`), '}'].join('\n');

const rolesCss = (roles: Roles, t: Tokens) =>
  (Object.entries(roles) as [Role, Paint][]).map(
    ([role, paint]) => `--${role}: ${paintCss(paint, t.primitives)};`,
  );

const axes = (a: Record<string, number>) =>
  Object.entries(a)
    .map(([tag, value]) => `"${tag}" ${value}`)
    .join(', ');

/** The whole generated stylesheet. Pure, so a test can emit from a changed copy of the tokens. */
export function emitCss(t: Tokens = tokens): string {
  const spacing = { ...t.layout, ...t.sizes, ...t.quarantine };
  const typeNames = Object.keys(t.type).map(kebab);
  const utilities = [
    ...typeNames.map((n) => `type-${n}`),
    'wordmark',
    ...Object.keys(wordmark.layers).map((n) => `wordmark-${n}`),
    ...Object.keys(wordmark.sizes).map((n) => `wordmark-${kebab(n)}`),
  ];
  const swatches = {
    ...Object.fromEntries(
      Object.keys(t.primitives).map((p) => [`primitive-${kebab(p)}`, `--primitive-${kebab(p)}`]),
    ),
    ...Object.fromEntries(Object.keys(t.surfaces.ground).map((r) => [r, `--${r}`])),
    ...Object.fromEntries(Object.keys(t.chart).map((c) => [c, `--chart-${c}`])),
  };

  return [
    '/* Generated by packages/tokens/emit.ts from packages/tokens/source.ts. Do not edit. */',
    // The default theme goes first, so an off-palette colour or a loose size has no utility.
    block('@theme static', [
      '--*: initial;',
      ...Object.entries(breakpoints).map(([n, px]) => `--breakpoint-${n}: ${px / 16}rem;`),
      ...Object.entries(fonts).map(
        ([n, f]) => `--font-${n}: var(${f.variable}), "${f.family}", ${f.fallback};`,
      ),
      '--default-font-family: var(--font-sans);',
      '--default-mono-font-family: var(--font-mono);',
      ...Object.entries(spacing).map(([n, px]) => `--spacing-${kebab(n)}: ${px}px;`),
      `--grid-template-columns-split: minmax(0, ${splitText}fr) minmax(0, ${12 - splitText}fr);`,
      `--grid-template-columns-split-flip: minmax(0, ${12 - splitText}fr) minmax(0, ${splitText}fr);`,
      `--stroke: ${stroke}px;`,
      `--default-border-width: ${stroke}px;`,
      `--default-outline-width: ${stroke}px;`,
      `--border-width-heavy: ${stroke * 2}px;`,
      ...Object.entries(opacity).map(([n, v]) => `--opacity-${n}: ${v * 100}%;`),
    ]),
    // inline: a utility must read the role where it's used, or it would stop flipping with the surface.
    block(
      '@theme inline',
      (Object.entries(roleUtilities) as [Role, string][]).map(
        ([role, name]) => `--color-${name}: var(--${role});`,
      ),
    ),
    `@source inline("${utilities.join(' ')}");`,
    [
      '@layer base {',
      block('*, ::before, ::after', [`border-radius: ${cornerRadius}px;`]),
      block(':root', [
        ...Object.entries(t.primitives).map(([n, hex]) => `--primitive-${kebab(n)}: ${hex};`),
        ...Object.entries(t.chart).map(([n, value]) => `--chart-${n}: ${value};`),
      ]),
      block(':root, [data-surface="ground"]', rolesCss(t.surfaces.ground, t)),
      ...(Object.entries(t.surfaces) as [SurfaceName, Roles][])
        .filter(([name]) => name !== 'ground')
        .map(([name, roles]) => block(`[data-surface="${name}"]`, rolesCss(roles, t))),
      block('[data-surface]', ['background-color: var(--surface);', 'color: var(--text-primary);']),
      ...Object.entries(swatches).map(([key, variable]) =>
        block(`[data-swatch="${key}"]`, [`background-color: var(${variable});`]),
      ),
      '}',
    ].join('\n'),
    ...Object.entries(t.type).map(([name, s]) =>
      block(`@utility type-${kebab(name)}`, [
        `font-family: var(--font-${s.font});`,
        `font-size: ${s.size}px;`,
        `line-height: ${s.line}px;`,
        `font-weight: ${s.weight};`,
        `letter-spacing: ${s.tracking}em;`,
        ...(s.axes ? [`font-variation-settings: ${axes(s.axes)};`] : []),
      ]),
    ),
    block('@utility figure-scale', [`zoom: ${figureScale};`]),
    // Non-scaling, so Stroke is the same width on a drawing at any of its sizes.
    block('@utility figure-stroke', [
      'stroke-width: var(--stroke);',
      'vector-effect: non-scaling-stroke;',
    ]),
    block('@utility figure-faint', ['stroke-opacity: var(--opacity-figure-line);']),
    block('@utility opacity-inactive', ['opacity: var(--opacity-inactive);']),
    block('@utility wordmark', [
      'display: inline-grid;',
      'font-family: var(--font-pixel);',
      'line-height: 1;',
      'letter-spacing: 0;',
      'white-space: nowrap;',
      'text-box: trim-both cap alphabetic;',
    ]),
    ...Object.entries(wordmark.layers).map(([layer, a]) =>
      block(`@utility wordmark-${layer}`, [
        'grid-area: 1 / 1;',
        'text-box: inherit;',
        `color: var(--${wordmark.roles[layer as keyof typeof wordmark.roles]});`,
        `font-variation-settings: ${axes(a)};`,
      ]),
    ),
    ...Object.entries(wordmark.sizes).map(([name, px]) =>
      block(`@utility wordmark-${kebab(name)}`, [`font-size: ${px}px;`]),
    ),
    // Outside any layer on purpose: a flower's own embedded <style> is unlayered, and an unlayered
    // rule beats every layer. Same variable names, higher specificity, so the bytes stay untouched.
    block('.flower-svg svg[data-petal]', [
      '--ink: var(--text-primary);',
      ...rendererVariables.map((n) => `--${n}: var(--chart-${n});`),
    ]),
    '',
  ].join('\n\n');
}

const channel = (v: number) => {
  const s = v / 255;
  return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
};
const rgb = (hex: string): [number, number, number] => [
  Number.parseInt(hex.slice(1, 3), 16),
  Number.parseInt(hex.slice(3, 5), 16),
  Number.parseInt(hex.slice(5, 7), 16),
];

function composite(paint: Paint, over: [number, number, number], t: Tokens) {
  if (typeof paint === 'string') return rgb(t.primitives[paint as Primitive]);
  const fg = rgb(t.primitives[paint.of]);
  return fg.map((c, i) => c * paint.alpha + (over[i] ?? 0) * (1 - paint.alpha)) as [
    number,
    number,
    number,
  ];
}

/** WCAG contrast of a paint over an opaque one. */
export function contrast(text: Paint, on: Paint, t: Tokens = tokens): number {
  const bg = composite(on, [255, 255, 255], t);
  const lum = ([r, g, b]: [number, number, number]) =>
    0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b);
  const [a, b] = [lum(composite(text, bg, t)), lum(bg)];
  return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

export interface ContrastResult {
  surface: SurfaceName;
  text: Role;
  on: Role;
  ratio: number;
}

export function contrastTable(t: Tokens = tokens): ContrastResult[] {
  return (Object.entries(t.surfaces) as [SurfaceName, Roles][]).flatMap(([surface, roles]) =>
    contrastPairs
      .filter((pair) => !pair.surfaces || pair.surfaces.includes(surface))
      .map(({ text, on }) => ({
        surface,
        text,
        on,
        ratio: contrast(roles[text], roles[on], t),
      })),
  );
}

export const contrastFailures = (t: Tokens = tokens) =>
  contrastTable(t).filter((r) => r.ratio < contrastMinimum);

if (import.meta.main) {
  const css = emitCss();
  if (process.argv.includes('--check')) {
    let failed = false;
    if (readFileSync(OUTPUT, 'utf8') !== css) {
      console.error(`tokens: ${OUTPUT} is stale. Run: node packages/tokens/emit.ts`);
      failed = true;
    }
    for (const r of contrastFailures()) {
      console.error(
        `tokens: on ${r.surface}, ${r.text} on ${r.on} is ${r.ratio.toFixed(2)}:1, under ${contrastMinimum}:1`,
      );
      failed = true;
    }
    if (failed) process.exit(1);
    console.log(`tokens: up to date, ${contrastTable().length} contrast pairs pass`);
  } else {
    writeFileSync(OUTPUT, css);
    console.log(`tokens: wrote ${OUTPUT}`);
  }
}
