// J4 (#49): what counts as a yes. When unsure it isn't one: the agent asks again, which is cheap.
import { describe, expect, test } from 'vitest';
import { isYes } from '../src/is-yes.ts';

describe('isYes', () => {
  test.each([
    'yes',
    'Yes.',
    'YES!',
    'yes!!!',
    '  yes  ',
    'yeah',
    'Yeah.',
    'yep',
    'yup',
    'sure',
    'Sure!',
    'ok',
    'OK.',
    'okay',
    'Okay, thanks',
    'go ahead',
    'Go ahead.',
    'do it',
    'Do it!',
    'please do',
    'yes please',
    'Yes, please.',
    'draw it',
    'Draw it please',
    'yes, go ahead',
    'yes go ahead please',
    'yeah, do it',
    'sure, draw it',
    'ok go ahead',
    'okay, do it please',
    'just do it',
    'of course',
    'sounds good',
    'sim',
    'Sim.',
    'sim, por favor',
    'pode',
    'Pode sim',
    'pode ser',
    'claro',
    'claro, pode',
    'Claro!',
    'sí',
    'um, yes',
  ])('%j is a yes', (said) => {
    expect(isYes(said)).toBe(true);
  });

  test.each([
    '',
    '   ',
    '...',
    'no',
    'No.',
    'nope',
    'not yet',
    'no thanks',
    'não',
    'nao',
    'yes but which one?',
    'yes but which one',
    'yes?',
    'ok?',
    'sure?',
    'do it?',
    'go ahead?',
    'sim?',
    'wait',
    'stop',
    'hold on',
    'ok wait',
    'yes, wait',
    'what does it cost',
    'what does it cost?',
    'please',
    'thanks',
    "don't do it",
    'do not do it',
    'do it later',
    'not now',
    'maybe',
    'hello',
    'near validators',
    'yes, draw near validators',
    'draw the bitcoin miners',
    'I said yes to the other one',
    'yes, although I would rather see the holders instead',
    'yes I think so but tell me what it costs first',
    'sim, mas qual',
    'yes '.repeat(40),
  ])('%j is not a yes', (said) => {
    expect(isYes(said)).toBe(false);
  });
});
