// The Postgres trial, on throwaway data in a throwaway Postgres container. Five questions, each answered by
// running it, not by reading:
//   1. Which of today's schema statements does Postgres take as they are?
//   2. Does the translated schema load?
//   3. Do today's rows copy across exactly, table by table?
//   4. Do the wallet seals still open, and still find their account?
//   5. Which of the store's SQL statements does Postgres accept? (PREPARE: parsed and planned, not run)
//   PETAL_WALLET_KEY=<hex> node pg-trial.ts <repo> <sqlite file> <pg container> <mode: load|check> <out file>
// load: questions 1 to 5 on a fresh database. check: only 3 and 4, on whatever the container holds
// (after a restore). Prints no key and no password.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';

const [repo, sqliteFile, pg, mode, outFile] = process.argv.slice(2) as [string, string, string, string, string];
const C = 'container';
const lines: string[] = [];
const say = (s: string) => {
  lines.push(s);
  console.log(s);
};

function psql(db: string, sql: string, stopOnError = true): { ok: boolean; out: string; err: string } {
  const r = spawnSync(
    C,
    ['exec', '-i', pg, 'psql', '-U', 'postgres', '-d', db, '-X', '-q', '-At', '-v', `ON_ERROR_STOP=${stopOnError ? 1 : 0}`, '-f', '-'],
    { input: sql, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  );
  return { ok: r.status === 0 && !/ERROR:/.test(r.stderr), out: r.stdout, err: r.stderr };
}

const { MIGRATIONS } = await import(`${repo}/packages/store/src/migrations.ts`);
const statements = (MIGRATIONS as string[]).flatMap((m) =>
  m.split(';').map((s) => s.replace(/--[^\n]*/g, '').trim()).filter(Boolean),
);

/** Today's SQLite schema, written for Postgres: the only two changes the trial needed. */
function translate(s: string): string {
  if (/^CREATE VIRTUAL TABLE search USING fts5/.test(s)) {
    return `CREATE TABLE search (
      rowid BIGINT PRIMARY KEY, title TEXT NOT NULL, text TEXT NOT NULL,
      tsv tsvector GENERATED ALWAYS AS (to_tsvector('simple', title || ' ' || text)) STORED
    ); CREATE INDEX search_tsv ON search USING GIN (tsv)`;
  }
  return s.replace(/\bid INTEGER PRIMARY KEY,/, 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,');
}

const { DatabaseSync } = process.getBuiltinModule('node:sqlite');
const lite = new DatabaseSync(sqliteFile, { readOnly: true });
const SHADOW = /^(sqlite_|search_(data|idx|content|docsize|config)$)/;
const tables = (lite.prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name").all() as { name: string }[])
  .map((r) => r.name)
  .filter((n) => !SHADOW.test(n));
const rowsOf = (t: string) =>
  lite.prepare(t === 'search' ? 'SELECT rowid, title, text FROM search' : `SELECT * FROM "${t}"`).all() as Record<string, unknown>[];
const lit = (v: unknown) =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' || typeof v === 'bigint' ? String(v) : `'${String(v).replaceAll("'", "''")}'`;

if (mode === 'load') {
  // 1. As they are
  psql('postgres', 'DROP DATABASE IF EXISTS asis; CREATE DATABASE asis; DROP DATABASE IF EXISTS petals; CREATE DATABASE petals;');
  const refused: string[] = [];
  for (const s of statements) {
    const r = psql('asis', `${s};`);
    if (!r.ok) refused.push(`${s.split('\n')[0]?.slice(0, 70)} → ${r.err.match(/ERROR:\s*(.*)/)?.[1] ?? r.err.trim()}`);
  }
  say(`1. As they are: Postgres took ${statements.length - refused.length} of ${statements.length} schema statements. Refused:`);
  for (const r of refused) say(`   - ${r}`);

  // 2. Translated
  // The store's own bookkeeping table, made by open.ts rather than by a migration.
  const bookkeeping = 'CREATE TABLE schema_migration (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL)';
  const schema = `${[bookkeeping, ...statements.map(translate)].join(';\n')};`;
  const loaded = psql('petals', `BEGIN;\n${schema}\nCOMMIT;`);
  say(`2. Translated schema (FTS5 → a tsvector column with a GIN index; the one auto-numbered id → IDENTITY): ${loaded.ok ? 'loaded' : `FAILED: ${loaded.err}`}`);

  // 3a. Copy the rows, in an order that respects references
  const order = ['meta', 'person', 'invite', 'wallet_binding', 'session', 'challenge', 'exploration', 'run'];
  const sorted = [...order.filter((t) => tables.includes(t)), ...tables.filter((t) => !order.includes(t))];
  const inserts: string[] = ['BEGIN;'];
  for (const t of sorted) {
    for (const row of rowsOf(t)) {
      const cols = Object.keys(row);
      inserts.push(`INSERT INTO "${t}" (${cols.map((c) => `"${c}"`).join(', ')}) VALUES (${cols.map((c) => lit(row[c])).join(', ')});`);
    }
  }
  inserts.push("SELECT setval(pg_get_serial_sequence('search_doc', 'id'), COALESCE((SELECT MAX(id) FROM search_doc), 0) + 1, false);");
  inserts.push('COMMIT;');
  const copied = psql('petals', inserts.join('\n'));
  say(`3a. Copied ${inserts.length - 3} rows from ${sorted.length} tables, in one transaction: ${copied.ok ? 'ok' : `FAILED: ${copied.err}`}`);
}

// 3. Row for row
const norm = (rows: Record<string, unknown>[]) =>
  rows.map((r) => JSON.stringify(Object.fromEntries(Object.keys(r).sort().map((k) => [k, r[k] === undefined ? null : r[k]])))).sort();
let same = 0;
const differ: string[] = [];
const counts: string[] = [];
for (const t of tables) {
  const sel = t === 'search' ? 'SELECT rowid, title, text FROM search' : `SELECT * FROM "${t}"`;
  const r = psql('petals', `SELECT COALESCE(json_agg(x), '[]') FROM (${sel}) x;`);
  const pgRows = r.ok ? (JSON.parse(r.out.trim() || '[]') as Record<string, unknown>[]) : [];
  const a = norm(rowsOf(t));
  const b = norm(pgRows);
  counts.push(`${t} ${a.length}/${b.length}`);
  if (r.ok && JSON.stringify(a) === JSON.stringify(b)) same++;
  else differ.push(`${t}: SQLite ${a.length} rows, Postgres ${b.length}${r.ok ? '' : ` (${r.err.trim()})`}`);
}
say(`3. Row for row: ${same} of ${tables.length} tables identical in SQLite and Postgres${differ.length ? `; differ: ${differ.join('; ')}` : ''}.`);
say(`   rows per table, SQLite/Postgres: ${counts.join(', ')}`);

// 4. Wallet seals
const { walletCipher, parseWalletKey } = await import(`${repo}/packages/agent/src/index.ts`);
const cipher = walletCipher(parseWalletKey(process.env.PETAL_WALLET_KEY as string));
const w = psql('petals', `SELECT COALESCE(json_agg(x), '[]') FROM (SELECT person, caip10_encrypted, caip10_hash FROM wallet_binding) x;`);
const wallets = JSON.parse(w.out.trim() || '[]') as { person: string; caip10_encrypted: string; caip10_hash: string }[];
const opened = wallets.map((b) => {
  try {
    const address = cipher.open(b.caip10_encrypted) as string;
    return { address, finds: cipher.index(address) === b.caip10_hash };
  } catch {
    return { address: '(does not open)', finds: false };
  }
});
say(`4. Wallet seals read from Postgres: ${opened.filter((o) => o.finds).length} of ${wallets.length} open with the server's key and still find their account: ${opened.map((o) => o.address).join(', ')}`);

if (mode === 'load') {
  // 5. Every SQL statement the store uses, parsed and planned by Postgres
  const src = readFileSync(`${repo}/packages/store/src/tables.ts`, 'utf8');
  const fill: [RegExp, string][] = [
    [/\$\{table\}/g, 'step'],
    [/\$\{column\}/g, 'exploration'],
    [/\$\{hidden \? 'NOT ' : ''\}/g, ''],
    [/\$\{SEARCH_HIT_OPEN\}/g, '['],
    [/\$\{SEARCH_HIT_CLOSE\}/g, ']'],
    [/\$\{kinds\.map\(\(\) => '\?'\)\.join\(', '\)\}/g, '?'],
  ];
  const found: string[] = [];
  const call = /db\.(get|all|run)(?:<[^(]*?>)?\(\s*/g;
  for (let m = call.exec(src); m; m = call.exec(src)) {
    const q = src[call.lastIndex];
    if (q !== "'" && q !== '"' && q !== '`') continue;
    let i = call.lastIndex + 1;
    let depth = 0;
    while (i < src.length) {
      const ch = src[i];
      if (ch === '\\') i += 2;
      else if (q === '`' && ch === '$' && src[i + 1] === '{') (depth++, (i += 2));
      else if (depth && ch === '}') (depth--, i++);
      else if (!depth && ch === q) break;
      else i++;
    }
    let sql = src.slice(call.lastIndex + 1, i);
    for (const [re, v] of fill) sql = sql.replace(re, v);
    found.push(sql);
  }
  const fails: string[] = [];
  let n = 0;
  for (const raw of found) {
    let k = 0;
    const sql = raw.replace(/\?/g, () => `$${++k}`);
    const r = psql('petals', `PREPARE s${++n} AS ${sql};`);
    if (!r.ok) fails.push(`${sql.replace(/\s+/g, ' ').slice(0, 90)} → ${r.err.match(/ERROR:\s*(.*)/)?.[1] ?? r.err.trim()}`);
  }
  say(`5. The store's SQL: Postgres parsed and planned ${found.length - fails.length} of ${found.length} statements as they are, with ? written as $1, $2… Refused:`);
  for (const f of fails) say(`   - ${f}`);
}

writeFileSync(outFile, `${lines.join('\n')}\n`);
