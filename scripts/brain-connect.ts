// The connect chapters as code (systems check, step 4; Elco's go): brain/chapters/connect-*.md are the only
// source of how each app connects. This writes packages/agent/src/connect.generated.ts from them, so
// /skill.md's setup, the keep commands /connect shows, and petal.mjs say exactly what the chapters say, and
// the web app (which has no brain/ at run time) carries them too.
//   node scripts/brain-connect.ts           writes the file
//   node scripts/brain-connect.ts --check   fails when the file isn't what the chapters make (check.sh)
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { headerOf } from '@petal/tools';

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'packages', 'agent', 'src', 'connect.generated.ts');
/** In the order /skill.md and /connect show them. */
export const CONNECT_IDS = [
  'connect-claude-code',
  'connect-codex',
  'connect-hermes',
  'connect-cloud',
];

export interface ConnectChapter {
  id: string;
  app: string;
  for: string;
  title: string;
  intro: string;
  sections: { heading: string; body: string }[];
}

/** One chapter, read: its header, its title, what comes before the first section, and each section. */
export function readConnect(text: string, id: string): ConnectChapter {
  const h = headerOf(text);
  const body = text
    .replace(/^---\n[\s\S]*?\n---\n/, '')
    .replace(/<!--[\s\S]*?-->\n?/g, '')
    .trim();
  const title = /^# (.+)$/m.exec(body)?.[1]?.trim() ?? id;
  const afterTitle = body.slice(body.indexOf('\n', body.indexOf(`# ${title}`)) + 1);
  const parts = afterTitle.split(/^## /m);
  const intro = (parts.shift() ?? '').trim();
  const sections = parts.map((p) => {
    const nl = p.indexOf('\n');
    return { heading: p.slice(0, nl).trim(), body: p.slice(nl + 1).trim() };
  });
  if (!h.app) throw new Error(`${id}: its header has no app`);
  return { id, app: h.app, for: h.for ?? '', title, intro, sections };
}

export function generated(): string {
  const chapters = CONNECT_IDS.map((id) =>
    readConnect(readFileSync(join(ROOT, 'brain', 'chapters', `${id}.md`), 'utf8'), id),
  );
  return `// Generated by scripts/brain-connect.ts from brain/chapters/connect-*.md. Don't edit it: change the chapters
// and run the script. scripts/check.sh fails when this is behind them. {site} and {host} are written in by
// whoever shows them.

export interface ConnectChapter {
  id: string;
  /** the app, as the chapter's header names it */
  app: string;
  for: string;
  title: string;
  intro: string;
  sections: { heading: string; body: string }[];
}

export const CONNECT_CHAPTERS: readonly ConnectChapter[] = ${JSON.stringify(chapters, null, 2)};
`;
}

if (import.meta.main) {
  const out = generated();
  if (process.argv.includes('--check')) {
    const now = readFileSync(OUT, 'utf8');
    if (now !== out) {
      console.error(
        'connect: packages/agent/src/connect.generated.ts is behind the connect chapters; run node scripts/brain-connect.ts',
      );
      process.exit(1);
    }
    console.log('connect: the generated words match the chapters');
  } else {
    writeFileSync(OUT, out);
    console.log(`connect: wrote ${OUT}`);
  }
}
